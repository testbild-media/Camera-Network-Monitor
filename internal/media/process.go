// ProcStatus describes the managed go2rtc process.
type ProcStatus struct {
	Managed   bool      `json:"managed"`
	Running   bool      `json:"running"`
	PID       int       `json:"pid,omitempty"`
	Restarts  int       `json:"restarts"`
	LastError string    `json:"lastError,omitempty"`
	StartedAt time.Time `json:"startedAt,omitempty"`
	Binary    string    `json:"binary,omitempty"`
}

// Process supervises a CNM-managed go2rtc instance.
type Process struct {
	cfg     func() *config.Config
	log     *slog.Logger
	started func() // called after every (re)start, e.g. Reconciler.Trigger

	changed chan struct{}

	mu     sync.Mutex
	status ProcStatus
}

// NewProcess creates the supervisor. Call Changed() on config updates.
func NewProcess(cfg func() *config.Config, log *slog.Logger, started func()) *Process {
	return &Process{cfg: cfg, log: log, started: started, changed: make(chan struct{}, 1)}
}

// Changed signals a configuration change.
func (p *Process) Changed() {
	select {
	case p.changed <- struct{}{}:
	default:
	}
}

// Status returns the process status.
func (p *Process) Status() ProcStatus {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.status
}

func procFingerprint(c *config.Config) string {
	m := c.System.Media
	return strings.Join([]string{strconv.FormatBool(m.ManageGo2rtc && m.Enabled), m.Go2rtcBin, m.FFmpegBin, m.Go2rtcConfigPath, m.Go2rtcAPIListen, m.Go2rtcRTSPListen, m.Go2rtcWebRTCListen, strconv.FormatBool(m.AllowWebRTC)}, "|")
}

// GenerateConfig renders the go2rtc configuration as one JSON object, which
// go2rtc takes directly on its command line ("-config {…}"). It contains no
// secrets. Streams are not part of it – CNM registers them at runtime
// through the API. External STUN servers are disabled (local only operation).
//
// Without a configuration file go2rtc cannot write registered streams back
// to disk (it otherwise patches every PUT /api/streams into its file), so
// the stream sources with the DVR credentials stay in memory only.
func GenerateConfig(c *config.Config) []byte {
	m := c.System.Media
	webrtc := ""
	if m.AllowWebRTC {
		webrtc = m.Go2rtcWebRTCListen
	}
	b, _ := json.Marshal(map[string]any{ // keys sorted: starts with {"api"
		"api":    map[string]any{"listen": m.Go2rtcAPIListen},
		"rtsp":   map[string]any{"listen": m.Go2rtcRTSPListen},
		"webrtc": map[string]any{"listen": webrtc, "ice_servers": []any{}},
		"ffmpeg": map[string]any{"bin": procutil.Resolve(m.FFmpegBin, "ffmpeg")},
		"log":    map[string]any{"level": "info", "format": "text"},
	})
	return b
}

// generatedHeader starts the configuration file of CNM 1.0.
const generatedHeader = "# Generated by Camera Network Monitor"

// Run supervises go2rtc until ctx is cancelled.
func (p *Process) Run(ctx context.Context) {
	for ctx.Err() == nil {
		c := p.cfg()
		m := c.System.Media
		if !m.ManageGo2rtc || !m.Enabled {
			p.mu.Lock()
			p.status = ProcStatus{Managed: false}
			p.mu.Unlock()
			select {
			case <-ctx.Done():
				return
			case <-p.changed:
				continue
			}
		}
		fp := procFingerprint(c)
		err := p.runOnce(ctx, c, fp)
		if ctx.Err() != nil {
			return
		}
		delay := time.Duration(m.Go2rtcRestartDelayMs) * time.Millisecond
		p.mu.Lock()
		p.status.Running = false
		p.status.PID = 0
		if err != nil {
			p.status.LastError = provider.Redact(err.Error())
		}
		p.status.Restarts++
		p.mu.Unlock()
		if err != nil {
			p.log.Warn("go2rtc stopped", "error", provider.Redact(err.Error()), "restart_in", delay.String())
		}
		select {
		case <-ctx.Done():
			return
		case <-time.After(delay):
		case <-p.changed:
		}
	}
}

func (p *Process) runOnce(ctx context.Context, c *config.Config, fp string) error {
	m := c.System.Media
	bin := procutil.Resolve(m.Go2rtcBin, "go2rtc")
	if err := os.MkdirAll(filepath.Dir(m.Go2rtcConfigPath), 0o750); err != nil {
		return err
	}
	// the file CNM 1.0 generated is no longer used
	if old, err := os.ReadFile(m.Go2rtcConfigPath); err == nil && bytes.HasPrefix(old, []byte(generatedHeader)) {
		_ = os.Remove(m.Go2rtcConfigPath)
	}
	pctx, cancel := context.WithCancel(ctx)
	defer cancel()
	cmd := exec.CommandContext(pctx, bin, "-config", string(GenerateConfig(c)))
	cmd.Dir = filepath.Dir(m.Go2rtcConfigPath)
	cmd.Env = append(os.Environ(), "GO2RTC_NO_UPDATE=1")
	procutil.Prepare(cmd, 2*time.Second)
	out, err := cmd.StdoutPipe()
	if err != nil {
		return err
	}
	cmd.Stderr = cmd.Stdout
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("go2rtc konnte nicht gestartet werden (%s): %w", bin, err)
	}
	p.mu.Lock()
	p.status = ProcStatus{Managed: true, Running: true, PID: cmd.Process.Pid, Restarts: p.status.Restarts, StartedAt: time.Now(), Binary: bin}
	p.mu.Unlock()
	p.log.Info("go2rtc started", "pid", cmd.Process.Pid, "binary", bin)
	go p.pipeLog(out)
	if p.started != nil {
		p.started()
	}
	exited := make(chan error, 1)
	go func() { exited <- cmd.Wait() }()
	for {
		select {
		case err := <-exited:
			if err == nil {
				err = fmt.Errorf("go2rtc beendet")
			}
			return err
		case <-p.changed:
			if procFingerprint(p.cfg()) != fp {
				p.log.Info("go2rtc settings changed, restarting")
				cancel()
				<-exited
				return nil
			}
		}
	}
}

func (p *Process) pipeLog(r io.Reader) {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 64<<10), 1<<20)
	for sc.Scan() {
		line := provider.Redact(sc.Text())
		lvl := slog.LevelDebug
		if strings.Contains(line, " ERR ") || strings.Contains(line, " WRN ") || strings.Contains(line, "error") {
			lvl = slog.LevelInfo
		}
		p.log.Log(context.Background(), lvl, "go2rtc", "line", line)
	}
}
