// swayConfig is a kiosk-only configuration: no bar, no borders, no key
// bindings, no XWayland, cursor hidden. Outputs and windows are managed by
// the agent through IPC.
const swayConfig = `# generated by Camera Network Monitor – do not edit
xwayland disable
default_border none
default_floating_border none
hide_edge_borders both
focus_follows_mouse no
mouse_warping none
focus_on_window_activation none
seat * hide_cursor 1000
`

// Compositor runs sway on the DRM backend.
type Compositor struct {
	Bin        string
	RuntimeDir string
	Log        *slog.Logger

	cmd     *exec.Cmd
	ipc     *IPC
	exited  chan struct{}
	wayland string
	version string
	tail    *lineTail
}

// Start launches sway and waits until its IPC socket answers.
func (c *Compositor) Start() error {
	if c.RuntimeDir == "" {
		return errors.New("XDG_RUNTIME_DIR fehlt – der Display-Dienst muss in einer Login-Sitzung (PAMName) laufen")
	}
	bin, err := exec.LookPath(c.Bin)
	if err != nil {
		return fmt.Errorf("sway nicht gefunden (%s) – Paket „sway“ installieren", c.Bin)
	}
	sock := filepath.Join(c.RuntimeDir, "cnm-sway.sock")
	_ = os.Remove(sock)
	cleanWaylandSockets(c.RuntimeDir)
	cfg := filepath.Join(c.RuntimeDir, "cnm-sway.conf")
	if err := os.WriteFile(cfg, []byte(swayConfig), 0o600); err != nil {
		return err
	}
	args, extraEnv := swayArgs(cfg, nvidiaLoaded())
	cmd := exec.Command(bin, args...)
	// a WAYLAND_DISPLAY/DISPLAY in the environment would make sway start nested
	cmd.Env = append(append(filterEnv(os.Environ(), "WAYLAND_DISPLAY", "DISPLAY", "SWAYSOCK"),
		"SWAYSOCK="+sock,
		"XDG_RUNTIME_DIR="+c.RuntimeDir,
		"XDG_SESSION_TYPE=wayland",
		"WLR_LIBINPUT_NO_DEVICES=1", // no keyboard/mouse required
	), extraEnv...)
	c.tail = newLineTail(20)
	stderr, err := cmd.StderrPipe()
	if err != nil {
		return err
	}
	cmd.Stdout = io.Discard
	setProcAttrs(cmd, false)
	if err := cmd.Start(); err != nil {
		return err
	}
	c.cmd = cmd
	c.exited = make(chan struct{})
	go c.tail.consume(stderr, func(line string) {
		if c.Log != nil {
			c.Log.Debug("sway", "line", line)
		}
	})
	go func() { _ = cmd.Wait(); close(c.exited) }()

	deadline := time.Now().Add(20 * time.Second)
	for {
		select {
		case <-c.exited:
			return fmt.Errorf("sway beendet sich beim Start: %s", c.tail.last())
		default:
		}
		if ipc, err := DialIPC(sock, time.Second); err == nil {
			c.ipc = ipc
			break
		}
		if time.Now().After(deadline) {
			c.Stop()
			return errors.New("sway antwortet nicht (IPC)")
		}
		time.Sleep(200 * time.Millisecond)
	}
	c.version, _ = c.ipc.Version()
	c.wayland = findWaylandSocket(c.RuntimeDir)
	if c.wayland == "" {
		c.Stop()
		return errors.New("Wayland-Socket von sway nicht gefunden")
	}
	return nil
}

// nvidiaLoaded reports whether the proprietary NVIDIA kernel driver is active.
func nvidiaLoaded() bool {
	_, err := os.Stat("/sys/module/nvidia_drm")
	return err == nil
}

// swayArgs returns the sway command line. sway refuses to start on the
// proprietary NVIDIA driver unless explicitly told so; hardware cursors are
// unreliable there (the cursor is hidden anyway). CNM_SWAY_ARGS adds
// arguments for troubleshooting.
func swayArgs(cfg string, nvidia bool) (args, env []string) {
	args = []string{"-c", cfg}
	if nvidia {
		args = append(args, "--unsupported-gpu")
		env = append(env, "WLR_NO_HARDWARE_CURSORS=1")
	}
	return append(args, strings.Fields(os.Getenv("CNM_SWAY_ARGS"))...), env
}

// Exited is closed when sway terminates.
func (c *Compositor) Exited() <-chan struct{} { return c.exited }

// LastError returns the last stderr line of sway.
func (c *Compositor) LastError() string {
	if c.tail == nil {
		return ""
	}
	return c.tail.last()
}

// Stop terminates sway.
func (c *Compositor) Stop() {
	if c.ipc != nil {
		_ = c.ipc.Close()
		c.ipc = nil
	}
	if c.cmd == nil || c.cmd.Process == nil {
		return
	}
	terminate(c.cmd, false)
	select {
	case <-c.exited:
	case <-time.After(3 * time.Second):
		kill(c.cmd, false)
		<-c.exited
	}
	c.cmd = nil
}

// cleanWaylandSockets removes stale Wayland sockets of earlier runs (the
// runtime directory belongs to the display user's session alone).
func cleanWaylandSockets(dir string) {
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), "wayland-") {
			_ = os.Remove(filepath.Join(dir, e.Name()))
		}
	}
}

func findWaylandSocket(dir string) string {
	entries, _ := os.ReadDir(dir)
	best, bestTime := "", time.Time{}
	for _, e := range entries {
		n := e.Name()
		if !strings.HasPrefix(n, "wayland-") || strings.HasSuffix(n, ".lock") {
			continue
		}
		info, err := e.Info()
		if err != nil || info.Mode()&os.ModeSocket == 0 {
			continue
		}
		if best == "" || info.ModTime().After(bestTime) {
			best, bestTime = n, info.ModTime()
		}
	}
	return best
}

func filterEnv(env []string, drop ...string) []string {
	out := env[:0:0]
	for _, kv := range env {
		k, _, _ := strings.Cut(kv, "=")
		skip := false
		for _, d := range drop {
			if k == d {
				skip = true
			}
		}
		if !skip {
			out = append(out, kv)
		}
	}
	return out
}

// lineTail keeps the last lines of a stream.
type lineTail struct {
	mu    sync.Mutex
	max   int
	lines []string
}

func newLineTail(max int) *lineTail { return &lineTail{max: max} }

func (t *lineTail) consume(r io.Reader, each func(string)) {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 64<<10), 1<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		t.mu.Lock()
		t.lines = append(t.lines, line)
		if len(t.lines) > t.max {
			t.lines = t.lines[len(t.lines)-t.max:]
		}
		t.mu.Unlock()
		if each != nil {
			each(line)
		}
	}
}

func (t *lineTail) last() string {
	t.mu.Lock()
	defer t.mu.Unlock()
	if len(t.lines) == 0 {
		return ""
	}
	l := t.lines[len(t.lines)-1]
	if len(l) > 300 {
		l = l[:300]
	}
	return l
}
